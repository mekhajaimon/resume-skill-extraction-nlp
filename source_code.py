import re

def extract_skills(text, skill_vocabulary):
    text = text.lower()
    extracted = []

    for skill in skill_vocabulary:
        skill_lower = skill.lower().strip()

        pattern = r'\b' + re.escape(skill_lower) + r'\b'

        if re.search(pattern, text):
            extracted.append(skill)

    return extracted

